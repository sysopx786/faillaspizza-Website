export type Copy = { [K in keyof typeof copy.en]: string };

const I18nContext = createContext<{
  lang: Lang;
  t: Copy;
  setLang: (lang: Lang) => void;
} | null>(null);

export const LANG_ORDER: Lang[] = ["en", "es", "pt"];

export const LANG_SHORT: Record<Lang, string> = {
  en: "EN",
  es: "ES",
  pt: "PT",
};

export const LANG_NAME: Record<Lang, string> = {
  en: "English",
  es: "Espa\u00f1ol",
  pt: "Portugu\u00eas",
};

export function otherLangs(current: Lang): Lang[] {
  return LANG_ORDER.filter((l) => l !== current);
}

export function loc(lang: Lang, en: string, es: string, pt?: string) {
  if (lang === "es") return es;
  if (lang === "pt") return pt ?? en;
  return en;
}

export function hoursLabelsFromCopy(t: Copy): HoursLabels {
  return {
    dayNames: [t.day_sun, t.day_mon, t.day_tue, t.day_wed, t.day_thu, t.day_fri, t.day_sat],
    closed: t.closed,
    openNow: t.openNow,
    until: t.until,
    opens: t.opens,
    tomorrow: t.tomorrow,
    callForHours: t.callForHours,
    andJoin: DEFAULT_HOURS_LABELS.andJoin,
  };
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getInitialLang);

  useLayoutEffect(() => {
    document.documentElement.lang = htmlLangAttr(lang);
    document.documentElement.setAttribute("data-lang", lang);
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      t: copy[lang],
      setLang: (next: Lang) => {
        setLangState(next);
        persistLang(next);
      },
    }),
    [lang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
  return ctx;
}
